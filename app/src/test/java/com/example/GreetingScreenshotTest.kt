            )
            Spacer(modifier = Modifier.height(4.dp))
            Text(
              text = "Modern Music Player",
              fontSize = 14.sp,
              color = Color.Gray
            )
          }
        }
      }
    }

    composeTestRule.onRoot().captureRoboImage(filePath = "src/test/screenshots/greeting.png")
